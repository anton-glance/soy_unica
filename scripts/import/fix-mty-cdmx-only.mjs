#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { toItem } from './map-product.mjs'
import { normalizePermalink } from './swoof.mjs'
import { verifyAgainstMigratedDatabase } from './verify-sql.mjs'

/**
 * One-time cleanup, not a recurring importer step.
 *
 * The first version of `catalog.mjs` had no branch signal at all and wrote
 * every product from the site into `mty` — including everything the site
 * only ever listed for CDMX. That is already live on production. This
 * script does not touch any database itself: it reads the same two files
 * `catalog.mjs` reads, works out which `mty` rows the site never actually
 * placed in Monterrey, and writes a preview and a DELETE, guarded three
 * ways, for a person to read and run by hand.
 *
 *   1. Never a seed row — the 16 items db/migrations/0002_seed.sql ships
 *      with, by their exact code, whatever the location data says about them.
 *   2. Never a row this importer didn't write — matched on the same
 *      `importado del sitio` marker `catalog.mjs` puts in `notes`, so a
 *      coincidentally-matching code the owner typed by hand is never touched.
 *   3. Never a row with any session or contract history — currently held,
 *      currently attached to a contract, or ever appearing in
 *      `contract_items`, `session_selections` or `session_favorites`. A
 *      catalog mistake is not a reason to unwrite a real sale or a real
 *      bride's favorites.
 *
 * This assumes the site's SKU and name for each product haven't changed
 * since the original import — the code is recomputed fresh, the same
 * deterministic way `codeFor()` always has, and matched against what's
 * already in `mty` by that code. If a product's SKU changed in between,
 * this won't find it, and that would show up as a mismatch between "roughly
 * 60" and what this script actually lists — worth a second look if so.
 *
 * Usage:
 *   node scripts/import/fix-mty-cdmx-only.mjs
 *   (needs docs/import/catalog-raw.json and docs/import/locations-raw.json already fetched — see catalog.mjs)
 */

const OUT = 'docs/import'
const RAW = `${OUT}/catalog-raw.json`
const LOCATIONS_RAW = `${OUT}/locations-raw.json`

/**
 * Verbatim from db/migrations/0002_seed.sql. Never touched by this fix,
 * whatever the location data says about a code that happens to collide —
 * this is about undoing what the importer wrote, not the owner's own
 * starting inventory.
 */
const SEED_CODES = [
  'p139', 'p142', 'p151', 's14', 's21', 's33', 'A12', 'A18', 'A24',
  'madelyn', 'aurora', 'isabella',
  'mantilla 039', 'mantilla 041', 'velo 07', 'crinolina 12',
]

for (const file of [RAW, LOCATIONS_RAW]) {
  if (!existsSync(file)) {
    console.error(`${file} does not exist. Run first:`)
    console.error('  node scripts/import/catalog.mjs --fetch --fetch-locations')
    process.exit(1)
  }
}

const raw = JSON.parse(readFileSync(RAW, 'utf8'))
const locations = JSON.parse(readFileSync(LOCATIONS_RAW, 'utf8'))
const mtySet = new Set(locations.mty?.permalinks ?? [])
const cdmxSet = new Set(locations.cdmx?.permalinks ?? [])

const mapped = raw.map(toItem)
const candidates = mapped.filter((p) => p.problems.length === 0 && !p.excluded)

const cdmxOnly = candidates.filter((p) => {
  const permalink = normalizePermalink(p.permalink)
  if (!permalink) return false
  return cdmxSet.has(permalink) && !mtySet.has(permalink)
})
const cdmxOnlySeed = cdmxOnly.filter((p) => SEED_CODES.includes(p.code))
const cdmxOnlyToRemove = cdmxOnly.filter((p) => !SEED_CODES.includes(p.code))

const q = (v) => `'${String(v).replace(/'/g, "''")}'`
const codeList = cdmxOnlyToRemove.map((p) => q(p.code)).join(', ') || "''"
const pesos = (cents) => `$${(cents / 100).toLocaleString('en-US', { minimumFractionDigits: 2 })}`

const CODE_FILTER = `code IN (${codeList})`
const SAFETY_GUARD = `notes LIKE 'importado del sitio%'
   AND held_by_session IS NULL
   AND contract_id IS NULL
   AND NOT EXISTS (SELECT 1 FROM contract_items      ci WHERE ci.item_id = items.id)
   AND NOT EXISTS (SELECT 1 FROM session_selections  ss WHERE ss.item_id = items.id)
   AND NOT EXISTS (SELECT 1 FROM session_favorites   sf WHERE sf.item_id = items.id)`

const sql = []
sql.push('-- Generated by scripts/import/fix-mty-cdmx-only.mjs. Do not edit by hand.')
sql.push('-- One-time cleanup: removes mty rows the site only ever listed for CDMX.')
sql.push('-- Read docs/import/fix-mty-cdmx-only.md FIRST — it lists exactly what this matches,')
sql.push('-- and separately, what it matched but is refusing to touch and why.')
sql.push('--')
sql.push('-- Run the two SELECT blocks below yourself and read their output before the DELETE')
sql.push('-- at the bottom of this file runs.')
sql.push('')
sql.push('-- ══════════════════════════ PREVIEW — read before deleting ══════════════════════════')
sql.push('-- What this WILL delete:')
sql.push('SELECT id, store_id, code, name, brand, price_cents, notes')
sql.push('  FROM items')
sql.push(` WHERE store_id = 'mty'`)
sql.push(`   AND ${CODE_FILTER}`)
sql.push(`   AND ${SAFETY_GUARD};`)
sql.push('')
sql.push('-- What matched the CDMX-only code list but is being LEFT ALONE, and why:')
sql.push('SELECT id, code, name, brand, price_cents,')
sql.push('       CASE')
sql.push("         WHEN notes NOT LIKE 'importado del sitio%' THEN 'not written by the site importer'")
sql.push("         WHEN held_by_session IS NOT NULL THEN 'currently held by an open kiosk session'")
sql.push("         WHEN contract_id IS NOT NULL THEN 'currently attached to a contract'")
sql.push("         WHEN EXISTS (SELECT 1 FROM contract_items ci WHERE ci.item_id = items.id) THEN 'appears in a contract'")
sql.push("         WHEN EXISTS (SELECT 1 FROM session_selections ss WHERE ss.item_id = items.id) THEN 'was chosen in a session'")
sql.push("         WHEN EXISTS (SELECT 1 FROM session_favorites sf WHERE sf.item_id = items.id) THEN 'was favorited in a session'")
sql.push("         ELSE 'unknown — look at this one by hand'")
sql.push('       END AS why_kept')
sql.push('  FROM items')
sql.push(` WHERE store_id = 'mty'`)
sql.push(`   AND ${CODE_FILTER}`)
sql.push(`   AND NOT (${SAFETY_GUARD});`)
sql.push('')
sql.push('-- ══════════════════════════ THE ACTUAL DELETE — run only after reading the preview above ══════════════════════════')
sql.push('DELETE FROM items')
sql.push(` WHERE store_id = 'mty'`)
sql.push(`   AND ${CODE_FILTER}`)
sql.push(`   AND ${SAFETY_GUARD};`)
const sqlText = sql.join('\n')

console.log('verifying the generated SQL against a fresh copy of db/migrations…')
try {
  verifyAgainstMigratedDatabase(sqlText)
} catch (err) {
  console.error(`\n✘ ${err.message}\n`)
  console.error('fix-mty-cdmx-only.sql was NOT written.')
  process.exit(1)
}
console.log('verified — the SQL applies cleanly (against a database with none of these rows to actually delete).\n')

// ─────────────────────────────────────────────────────────────── report ──
const lines = []
const say = (s = '') => lines.push(s)
say('# Fix: mty rows that are actually CDMX-only')
say()
say('**None of this has been written to any database.** This reads the same two files')
say('`catalog.mjs` reads and works out, from the site\'s own SWOOF-filtered listings, which')
say('rows already in `mty` were never actually placed there by the site — see the header of')
say('`scripts/import/fix-mty-cdmx-only.mjs` for exactly what is guarded and why.')
say()
say('## Summary')
say()
say('| | |')
say('|---|---|')
say(`| CDMX-only products found | ${cdmxOnly.length} |`)
say(`| of those, seed rows (never touched, whatever the location says) | ${cdmxOnlySeed.length} |`)
say(`| **rows this DELETE targets** | **${cdmxOnlyToRemove.length}** |`)
say(`| catalog value of what would be removed | ${pesos(cdmxOnlyToRemove.reduce((n, p) => n + p.price_cents, 0))} |`)
say()
if (cdmxOnlySeed.length > 0) {
  say('## Seed rows that happen to be CDMX-only per the site — left alone')
  say()
  say('These are never in scope for this fix regardless of what the location data says: they are')
  say('the prototype\'s own starting inventory, not something the importer wrote.')
  say()
  say('| code | model |')
  say('|---|---|')
  for (const p of cdmxOnlySeed) say(`| \`${p.code}\` | ${p.name} |`)
  say()
}
if (cdmxOnlyToRemove.length > 0) {
  const byBrand = new Map()
  for (const p of cdmxOnlyToRemove) {
    const key = p.brand ?? '(sin marca)'
    byBrand.set(key, (byBrand.get(key) ?? 0) + 1)
  }
  say('## By brand')
  say()
  say('| brand | rows |')
  say('|---|---|')
  for (const [brand, n] of [...byBrand.entries()].sort((a, b) => b[1] - a[1])) say(`| ${brand} | ${n} |`)
  say()
  say('## What this would delete, by code')
  say()
  say('The exact list the `code IN (...)` in the SQL matches against. A row here is only actually')
  say('deleted if it also clears the three guards — run the first `SELECT` in the `.sql` file to')
  say('see which of these are really about to go, and the second to see which ones this is')
  say(`refusing to touch and why (a session or a contract touched it since it was imported).`)
  say()
  say('| code | model | brand | price |')
  say('|---|---|---|---|')
  for (const p of cdmxOnlyToRemove) say(`| \`${p.code}\` | ${p.name} | ${p.brand ?? '—'} | ${pesos(p.price_cents)} |`)
  say()
} else {
  say('Nothing to remove: no product the site lists as CDMX-only, and not a seed row, was found.')
  say()
}
say('## Applying it')
say()
say('Local first, always:')
say()
say('```')
say('npx wrangler d1 execute soy-unica --local --persist-to .wrangler/state \\')
say('  --file docs/import/fix-mty-cdmx-only.sql')
say('```')
say()
say('Read the two `SELECT` blocks\' output before the `DELETE` at the bottom runs. For production,')
say('the same command with `--remote` in place of `--local --persist-to .wrangler/state`.')
say()
say('This leaves the corresponding `item_photos` rows cascade-deleted automatically (the schema')
say('does that), but the underlying `files` rows — the R2 metadata — and the actual objects in R2')
say('are not touched by this SQL. They become orphaned, not broken: nothing points a bride or a')
say('seller at them anymore, they just sit in storage. Cleaning those up is a separate, lower-')
say('priority pass, not blocking.')

mkdirSync(OUT, { recursive: true })
writeFileSync(`${OUT}/fix-mty-cdmx-only.md`, lines.join('\n'))
writeFileSync(`${OUT}/fix-mty-cdmx-only.sql`, sqlText)
console.log(`report → ${OUT}/fix-mty-cdmx-only.md`)
console.log(`sql    → ${OUT}/fix-mty-cdmx-only.sql   (targets ${cdmxOnlyToRemove.length} codes, guarded)`)
